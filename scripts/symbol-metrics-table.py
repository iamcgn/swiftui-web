#!/usr/bin/env python3
"""Generate Packages/WebGraphics/Sources/WebGraphics/Text/SystemSymbolMetricsTable.swift: the
built-in layout sizes of the common SF Symbols (the `symbol/catalog-*` fixtures' names) at the
macOS text-style point sizes (regular weight), at 13 pt semibold and bold, and at 13 pt with the
small and large image scales, taken from the full-catalog measurement
Fixtures/Goldens/symbol/metrics-full.txt (`scripts/symbol-metrics-full.swift`, every symbol of
the system catalog through SwiftUI). The full file ships as a runtime asset the hosts load on
the first symbol outside the built-in set (sw-symbols); the catalog goldens check the table.

    python3 scripts/symbol-metrics-table.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOLDENS = ROOT / "Fixtures/Goldens/symbol"
OUT = ROOT / "Packages/WebGraphics/Sources/WebGraphics/Text/SystemSymbolMetricsTable.swift"

POINT_SIZES = [10, 11, 12, 13, 15, 17, 22, 26]
VARIANTS = [str(s) for s in POINT_SIZES] + ["13-semibold", "13-bold", "13-small", "13-large"]


def fmt(v):
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


FONT_KEYS = {str(s): f"system:{s}:400:default||Star" for s in POINT_SIZES}
FONT_KEYS.update({"13-semibold": "system:13:600:default||Star", "13-bold": "system:13:700:default||Star",
                  "13-small": "system:13:400:default||Star", "13-large": "system:13:400:default||Star"})


def main():
    full = {}
    for line in (GOLDENS / "metrics-full.txt").read_text().split("\n"):
        parts = line.split()
        if len(parts) == 1 + 3 * len(VARIANTS): full[parts[0]] = parts[1:]
    source = (ROOT / "Fixtures/Sources/Symbol/SymbolFixtures.swift").read_text()
    start = source.index("catalogNames: [String] = [") + len("catalogNames: [String] = [")
    body = source[start : source.index("\n    ]", start)]
    names = sorted(set(re.findall(r'"([^"]+)"', body)))
    missing = [n for n in names if n not in full]
    if missing: print(f"not in metrics-full.txt: {missing}")
    names = [n for n in names if n in full]
    meta = json.loads((GOLDENS / "catalog-13" / "meta.json").read_text())
    lines = [f'{name} {" ".join(full[name])}' for name in names]
    # The iOS 26 generation (the simulator goldens' OS): the catalog goldens measured on macOS
    # 26.2, whose symbol sizes the iOS 26 simulator shares; macOS 27 lays several sizes out 1 pt taller.
    legacy = (GOLDENS / "metrics-26.txt").read_text().strip()
    body = f'''// Generated by scripts/symbol-metrics-table.py from Fixtures/Goldens/symbol/metrics-full.txt; do not edit.
// macOS {meta["macOS"]}, SwiftUI {meta["swiftUI"]}.
//
// The layout size of `Image(systemName:)` for each built-in symbol: width, height and descent
// (how far the frame's bottom sits below the text baseline) triples at
// the point sizes {POINT_SIZES} (regular weight, medium image scale), then at 13 pt semibold,
// 13 pt bold, 13 pt with the small image scale and 13 pt with the large image scale. Every other
// symbol of the catalog is in the `symbol-metrics.txt` asset (`extended`, loaded by the hosts).

public enum SystemSymbolMetricsTable {{
    public static let pointSizes: [Double] = [{", ".join(str(s) for s in POINT_SIZES)}]
    public static let count = {len(names)}
    /// Values per line after the name.
    public static let valueCount = {3 * len(VARIANTS)}

    /// Parsed from `blob` on first use (a literal this large would compile into code).
    public static let sizes: [String: [Double]] = parse(blob)
    /// The OS 26 generation's sizes for the built-in symbols (`Fixtures/Goldens/symbol/metrics-26.txt`,
    /// measured on macOS 26.2 and shared by the iOS 26 simulator): several sizes lay out 1 pt
    /// shorter than on OS 27.
    public static let legacySizes: [String: [Double]] = parse(legacyBlob)

    /// The full catalog's sizes once a host has loaded the asset (`load(text:)`).
    nonisolated(unsafe) public private(set) static var extended: [String: [Double]] = [:]
    public static var isExtended: Bool {{ !extended.isEmpty }}

    /// Loads the full-catalog text (one symbol per line: name, then the values).
    public static func load(text: String) {{
        extended = parse(text)
    }}

    /// The values for `name`: the built-in table first (the OS 26 one when `legacy`), then the
    /// loaded catalog (OS 27 sizes).
    public static func values(named name: String, legacy: Bool = false) -> [Double]? {{
        (legacy ? legacySizes[name] : nil) ?? sizes[name] ?? extended[name]
    }}

    static func parse(_ text: String) -> [String: [Double]] {{
        var sizes: [String: [Double]] = [:]
        for line in text.split(separator: "\\n") {{
            let parts = line.split(separator: " ")
            guard parts.count == 1 + valueCount else {{ continue }}
            sizes[String(parts[0])] = parts.dropFirst().compactMap {{ Double($0) }}
        }}
        return sizes
    }}

    /// name, then width height descent per variant, one symbol per line.
    private static let blob = """
'''
    OUT.write_text(body + "\n".join(lines) + "\n\"\"\"\n\n    private static let legacyBlob = \"\"\"\n" + legacy + "\n\"\"\"\n}\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(names)} symbols, {len(VARIANTS)} variants")


if __name__ == "__main__":
    main()
