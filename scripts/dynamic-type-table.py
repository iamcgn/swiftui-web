#!/usr/bin/env python3
"""Regenerates Packages/WebGraphics/Sources/WebGraphics/Text/DynamicTypeTable.swift from
Fixtures/Goldens/uikit/font-metrics.json: each text style's point size and line height
(ascender − descender + leading, UIFont.lineHeight) at every content size category. SwiftUI's
iOS text styles take the point size and `@ScaledMetric` scales by the line-height ratio to
the large category (sw-dynamic-type, measured on `ios/text/dynamic-*`)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
source = root / "Fixtures/Goldens/uikit/font-metrics.json"
data = json.loads(source.read_text())
scaled = data["scaledTextStyles"]
styles = ["largeTitle", "title", "title2", "title3", "headline", "subheadline", "body", "callout", "footnote", "caption", "caption2"]
categories = ["XS", "S", "M", "L", "XL", "XXL", "XXXL", "AXM", "AXL", "AXXL", "AXXXL", "AXXXXL"]

def fmt(v):
    return repr(float(v)) if isinstance(v, float) and not float(v).is_integer() else str(int(v))

lines = [
    f"// Generated by scripts/dynamic-type-table.py from {source.relative_to(root)}",
    f"// ({data.get('host', 'iPhone simulator')}). Do not edit by hand.",
    "",
    "extension SystemFontMetricsTables {",
    "    /// Each iOS text style at every content size category (Dynamic Type): the point size and",
    "    /// the font's line height (ascender − descender + leading). Keys are UIKit's short names",
    '    /// ("XS", "S", "M", "L", "XL", "XXL", "XXXL", "AXM", "AXL", "AXXL", "AXXXL", "AXXXXL").',
    "    public static let iOSDynamicTypeSizes: [FontTextStyle: [String: (pointSize: CGFloat, lineHeight: CGFloat)]] = [",
]
for s in styles:
    entries = []
    for c in categories:
        m = scaled[s][c]
        entries.append(f'"{c}": ({fmt(m["pointSize"])}, {fmt(m["ascender"] - m["descender"] + m["leading"])})')
    lines.append(f"        .{s}: [{', '.join(entries)}],")
lines += ["    ]", "}", ""]
out = root / "Packages/WebGraphics/Sources/WebGraphics/Text/DynamicTypeTable.swift"
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)}")
