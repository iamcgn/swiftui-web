    @Test func theArchiveNamesTheClassAsIOSDoes() throws {
        let data = try NSKeyedArchiver.archivedData(withRootObject: UIColor.red, requiringSecureCoding: true)
        let plist = try PropertyListSerialization.propertyList(from: data, options: [], format: nil) as? [String: Any]
        let objects = plist?["$objects"] as? [Any] ?? []
        let names = objects.compactMap { ($0 as? [String: Any])?["$classname"] as? String }
