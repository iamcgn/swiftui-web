// UIColor as a keyed archive: its components under iOS's keys, read back as the same colour,
// a dynamic colour's dark value kept, and an archive iOS writes for an RGB colour read as one
// (IceCubes keeps its theme's colours as base64 archives in user defaults).
import Testing
import UIKit
import WebGraphicsHeadless

@Suite struct ColorArchiveTests {
    #if os(WASI) || canImport(Darwin)
    @Test func aColourRoundTrips() throws {
        let color = UIColor(red: 0.25, green: 0.5, blue: 0.75, alpha: 0.5)
        let data = try NSKeyedArchiver.archivedData(withRootObject: color, requiringSecureCoding: true)
        let copy = try NSKeyedUnarchiver.unarchivedObject(ofClass: UIColor.self, from: data)
        #expect(copy?.light == RGBA(red: 0.25, green: 0.5, blue: 0.75, alpha: 0.5))
        #expect(copy?.dark == copy?.light)
    }

    @Test func aDynamicColourKeepsItsDarkValue() throws {
        let color = UIColor(_light: RGBA(red: 1, green: 1, blue: 1), _dark: RGBA(red: 0, green: 0, blue: 0))
        let data = try NSKeyedArchiver.archivedData(withRootObject: color, requiringSecureCoding: true)
        let copy = try NSKeyedUnarchiver.unarchivedObject(ofClass: UIColor.self, from: data)
        #expect(copy?.light == RGBA(red: 1, green: 1, blue: 1))
        #expect(copy?.dark == RGBA(red: 0, green: 0, blue: 0))
    }
    #endif

