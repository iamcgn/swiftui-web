#!/usr/bin/env python3
"""Joins Apple's surface, SwiftUIWeb's surface and the compile sweep into one ranked gap list
(Tools/Coverage/README.md).

  report.py --apple apple.json --ours ours.json --plan plan.json --sweep results-*.json \\
            --md coverage.md --json coverage.json

Every section is a count from the inputs; nothing is weighted by hand. The ranking that matters
is "how many corpus apps hit it": an API a third of the apps use outranks a hundred that none do.
"""
import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from sweep import APPLE  # noqa: E402

HEADLINE = ["SwiftUI", "SwiftUICore", "Observation", "Combine", "SwiftData", "Charts", "MapKit",
            "CoreLocation", "AVKit", "WebKit", "UserNotifications", "Speech", "SafariServices",
            "AVFoundation", "UIKit", "Foundation"]
SWIFTUI = {"SwiftUI", "SwiftUICore"}


def basename(component):
    return component.split("(")[0]


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "—"


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apple"); ap.add_argument("--ours"); ap.add_argument("--plan")
    ap.add_argument("--sweep", nargs="*", default=[]); ap.add_argument("--commit", default="")
    ap.add_argument("--md", required=True); ap.add_argument("--json", required=True)
    args = ap.parse_args()

    apple = json.loads(Path(args.apple).read_text()) if args.apple and Path(args.apple).exists() else None
    ours = json.loads(Path(args.ours).read_text()) if args.ours and Path(args.ours).exists() else None
    plan = json.loads(Path(args.plan).read_text()) if args.plan and Path(args.plan).exists() else {"apps": []}
    sweep = []
    for f in args.sweep:
        try:
            sweep.append(json.loads(Path(f).read_text()))
        except Exception as e:
            print(f"{f}: {e}", file=sys.stderr)
    apps = [a for r in sweep for a in r.get("apps", [])]
    out, data = [], {}
    out.append("# API coverage and the compile sweep\n")
    out.append(f"Generated by `Tools/Coverage/report.py` from the Coverage workflow"
               + (f" at {args.commit[:10]}" if args.commit else "")
               + (f", against Apple's {apple['meta'].get('sdk')} SDK" if apple and apple.get("meta", {}).get("sdk") else "")
               + ". Method and caveats: `Tools/Coverage/README.md`.\n")

    # MARK: surface diff
    our_keys = set((ours or {}).get("modules", {}).get("all", {}))
    our_bases = {basename(k.split(".")[-1]) for k in our_keys}
    our_types = {k.split(".")[0] for k in our_keys}
    missing_by_module = {}
    if apple and ours:
        rows = []
        for m in HEADLINE + sorted(set(apple["modules"]) - set(HEADLINE)):
            keys = apple["modules"].get(m)
            if not keys:
                continue
            cur = [k for k, v in keys.items() if not v["deprecated"]]
            dep = [k for k, v in keys.items() if v["deprecated"]]
            have = sum(1 for k in cur if k in our_keys)
            rows.append((m, len(cur), have, pct(have, len(cur)), f"{sum(1 for k in dep if k in our_keys)}/{len(dep)}"))
            missing_by_module[m] = sorted(k for k in cur if k not in our_keys)
        out.append("## Apple's surface against SwiftUIWeb's\n")
        out.append("A key is a declaration's name with its argument labels (`View.padding(_:_:)`); overloads that "
                   "differ only in types count once. Present means the key exists, not that it behaves: the "
                   "support matrix says that. Deprecated keys are counted apart.\n")
        out.append(md_table(["Module", "Current keys", "Present", "Coverage", "Deprecated present"], rows) + "\n")
        data["coverage"] = [dict(zip(["module", "keys", "present", "coverage", "deprecated"], r)) for r in rows]
        data["missing"] = missing_by_module

    # MARK: the corpus
    if apps:
        out.append("## The corpus\n")
        out.append("Each app built for wasm from its sources at the commit shown, with every `import` of a module "
                   "wasm does not have taken out so the build reaches the code below it (a measurement only; "
                   "decision 0021's standard is unchanged). The app's pinned packages build from source with it; a "
                   "module whose package failed is built without that package, its imports taken out the same way, "
                   "so the module's own errors still count. `In packages` is how many of the errors are in the packages' "
                   "own files.\n")
        rows = []
        for a in sorted(apps, key=lambda a: a["name"]):
            st = Counter(t["status"] for t in a["targets"])
            errs = sum(len(t["errors"]) for t in a["targets"])
            fw = [m for m in a.get("stripped", []) if m in APPLE]
            third = [m for m in a.get("stripped", []) if m not in APPLE]
            result = "compiles" if st.get("ok") == len(a["targets"]) else ", ".join(f"{v} {k}" for k, v in st.items())
            rows.append((a["name"] + (" (control)" if a.get("control") else ""), f"[{(a.get('sha') or '')[:7]}](https://github.com/{a['repo']}/tree/{a.get('sha')})",
                         a.get("files"), "/".join(a.get("modes", [])), result, errs,
                         ", ".join(fw) or "—", len(third), a.get("os_condition_files", 0),
                         sum(1 for t in a["targets"] for e in t["errors"] if e.get("package"))))
        failed = [a for a in plan.get("apps", []) if not a.get("sha")]
        out.append(md_table(["App", "Commit", "Files", "Mode", "Modules", "Errors", "Apple frameworks missing",
                             "Third-party packages", "Files with os()", "In packages"], rows) + "\n")
        if failed:
            out.append("Not cloned: " + ", ".join(f"{a['name']} ({a.get('error', '')[:80]})" for a in failed) + "\n")
        out.append("`Files with os()` counts files with an `#if os(iOS)` (or another Apple platform) condition: on wasm "
                   "every such condition is false, so those files compile their non-iOS branch.\n")

        # Frameworks and packages, by apps.
        fw, third = Counter(), Counter()
        for a in apps:
            for m in a.get("stripped", []):
                (fw if m in APPLE else third)[m] += 1
        out.append("### Modules the apps import that wasm does not have\n")
        out.append(md_table(["Apple framework", "Apps"], fw.most_common()) + "\n")
        out.append(md_table(["Third-party package", "Apps"], third.most_common(25)) + "\n")
        data["frameworks"] = fw.most_common(); data["third_party"] = third.most_common()

        # Errors, aggregated by key across apps.
        apple_top = set()
        apple_bases = set()
        if apple:
            for keys in apple["modules"].values():
                for k in keys:
                    parts = k.split(".")
                    if len(parts) == 1:
                        apple_top.add(basename(parts[0]))
                    apple_bases.add(basename(parts[-1]))
        by_key = defaultdict(lambda: {"apps": set(), "count": 0, "example": None})
        for a in apps:
            assets = {norm(x) for x in a.get("asset_names", [])}
            assets |= {n[:-5] for n in assets if n.endswith("color")} | {n[:-5] for n in assets if n.endswith("image")}
            entities = set(a.get("model_entities", []))
            third_names = {m for m in a.get("stripped", []) if m not in APPLE}
            for t in a["targets"]:
                for e in t["errors"]:
                    cat, key = e["category"], e["key"]
                    member = key.split(".")[-1] if cat == "member" else key
                    if cat == "member" and norm(member) in assets:
                        origin = "Xcode asset symbol"
                    elif cat in ("name", "type") and key in entities:
                        origin = "Core Data codegen"
                    elif cat == "attribute":
                        origin = "Apple" if key[1:] in apple_top or key[1:] in apple_bases else ("third-party or app" if third_names else "app or Xcode")
                    elif cat in ("name", "type"):
                        origin = "Apple" if key in apple_top or key in apple_bases else ("third-party or app" if third_names else "app or Xcode")
                    elif cat == "member":
                        origin = "Apple" if member in apple_bases else "app or third-party"
                    else:
                        origin = ""
                    b = by_key[(cat, key)]
                    b["apps"].add(a["name"]); b["count"] += 1; b["origin"] = origin
                    b["example"] = b["example"] or f"{a['name']}: {e['file']}:{e['line']}: {e['msg'][:140]}"
        ranked = sorted(by_key.items(), key=lambda kv: (-len(kv[1]["apps"]), -kv[1]["count"]))
        out.append("### What the builds hit, by how many apps\n")
        out.append("`Apple` means the name exists in Apple's surface, so SwiftUIWeb lacks it or lacks this form of it. "
                   "Errors that follow from a missing third-party package or Xcode-generated code are kept, labelled.\n")
        for cats, title in ((("name", "type", "attribute", "member", "availability", "conformance"), "Missing names"),
                            (("isolation",), "Isolation and concurrency"),
                            (("signature", "other"), "Signatures and everything else")):
            rows = [(f"`{k}`", c, len(v["apps"]), v["count"], v.get("origin", ""), v["example"])
                    for (c, k), v in ranked if c in cats][:60]
            if rows:
                out.append(f"#### {title}\n")
                out.append(md_table(["Key", "Kind", "Apps", "Errors", "Origin", "First seen"], rows) + "\n")
        # One key, "cannot infer contextual base in reference to member '…'", is the largest
        # group, and its key hides the member: `.v17`, `.insetGrouped`. Most follow from a missing
        # type or overload upstream; the members show which.
        inferred = defaultdict(lambda: {"apps": set(), "count": 0, "example": None})
        for a in apps:
            for t in a["targets"]:
                for e in t["errors"]:
                    m = re.match(r"cannot infer contextual base in reference to member '([^']+)'", e["msg"])
                    if m:
                        b = inferred[m.group(1)]
                        b["apps"].add(a["name"]); b["count"] += 1
                        b["example"] = b["example"] or f"{a['name']}: {e['file']}:{e['line']}"
        if inferred:
            rows = [(f"`.{k}`", len(v["apps"]), v["count"], v["example"])
                    for k, v in sorted(inferred.items(), key=lambda kv: (-len(kv[1]["apps"]), -kv[1]["count"], kv[0]))][:50]
            out.append("#### The members behind \"cannot infer contextual base\"\n")
            out.append(md_table(["Member", "Apps", "Errors", "First seen"], rows) + "\n")
            data["inferred_members"] = [{"member": k, "apps": sorted(v["apps"]), "count": v["count"]} for k, v in inferred.items()]
        # Most errors sit in a few apps, and within each app in a few files: one type or package
        # that fails takes every line using it with it. The heaviest apps' files and keys show
        # the root to fix first.
        heavy = sorted(apps, key=lambda a: -sum(len(t["errors"]) for t in a["targets"]))[:6]
        heavy = [a for a in heavy if any(t["errors"] for t in a["targets"])]
        if heavy:
            out.append("#### Where the heaviest apps' errors are\n")
            data["heavy_apps"] = []
            for a in heavy:
                files, keys = Counter(), Counter()
                for t in a["targets"]:
                    for e in t["errors"]:
                        files[e["file"]] += 1
                        keys[f"{e['category']}: {e['key']}"] += 1
                total = sum(files.values())
                third = [m for m in a.get("stripped", []) if m not in APPLE]
                out.append(f"**{a['name']}**: {total} errors in {len(files)} files"
                           + (f"; {len(a['packages'])} packages built from source" if a.get("packages") else "")
                           + (f"; modules taken out: {', '.join(sorted(third))}" if third else "") + "\n")
                out.append(md_table(["File", "Errors"], [(f"`{f}`", n) for f, n in files.most_common(8)]) + "\n")
                out.append(md_table(["Key", "Errors"], [(f"`{k}`", n) for k, n in keys.most_common(8)]) + "\n")
                data["heavy_apps"].append({"app": a["name"], "errors": total, "files": files.most_common(20), "keys": keys.most_common(20)})
        data["errors"] = [{"category": c, "key": k, "apps": sorted(v["apps"]), "count": v["count"],
                           "origin": v.get("origin", ""), "example": v["example"]} for (c, k), v in ranked]

    # MARK: names we have nowhere, by use in the corpus
    if apple and ours:
        tokens = {a["name"]: set(a.get("tokens", [])) for a in apps}
        absent = defaultdict(list)
        for m in HEADLINE:
            for k in missing_by_module.get(m, []):
                parts = k.split(".")
                base = basename(parts[-1])
                if base in ("init", "subscript", "callAsFunction") or not re.match(r"^[A-Za-z]", base):
                    continue
                top = len(parts) == 1
                if (top and base in our_types) or (not top and base in our_bases):
                    continue
                absent[(m, base)].append(k)
        rows = []
        for (m, base), keys in absent.items():
            users = sorted(n for n, toks in tokens.items() if base in toks)
            rows.append((len(users), m, base, keys, users))
        rows.sort(key=lambda r: (-r[0], HEADLINE.index(r[1]), r[2]))
        out.append("## Apple names SwiftUIWeb has nowhere, by how many corpus apps mention them\n")
        out.append("A name counts once per module, under any type. Mentions are the identifier appearing in the "
                   "app's sources (comments aside), so a common word over-counts; a distinctive one does not.\n")
        out.append(md_table(["Apps", "Module", "Name", "Keys"],
                            [(r[0], r[1], f"`{r[2]}`", ", ".join(f"`{k}`" for k in r[3][:3]) + (f" +{len(r[3]) - 3}" if len(r[3]) > 3 else ""))
                             for r in rows[:120]]) + "\n")
        data["absent_names"] = [{"apps": r[0], "module": r[1], "name": r[2], "keys": r[3], "users": r[4]} for r in rows]

        # SwiftUI's missing keys by type.
        by_type = defaultdict(list)
        for m in SWIFTUI:
            for k in missing_by_module.get(m, []):
                by_type[k.split(".")[0]].append(k)
        rows = sorted(by_type.items(), key=lambda kv: -len(kv[1]))[:50]
        out.append("## SwiftUI's missing keys by type\n")
        out.append(md_table(["Type", "Missing", "Examples"],
                            [(f"`{t}`", len(ks), ", ".join(f"`{k.split('.', 1)[-1]}`" for k in ks[:6])) for t, ks in rows]) + "\n")

    Path(args.md).write_text("\n".join(out))
    Path(args.json).write_text(json.dumps(data, indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    main()
